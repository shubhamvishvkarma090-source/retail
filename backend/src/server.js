import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import {connectDB} from "./config/db.js";
import authRoutes from "./routes/auth.js";
import productRoutes from "./routes/products.js";
import inventoryRoutes from "./routes/inventory.js";
import salesRoutes from "./routes/sales.js";
import reportRoutes from "./routes/reports.js";
import {notFound,errorHandler} from "./middleware/errors.js";
const app=express();
app.use(helmet());app.use(cors({origin:process.env.CLIENT_URL||"http://localhost:3000"}));app.use(express.json({limit:"1mb"}));
app.use("/api/auth/login",rateLimit({windowMs:15*60*1000,max:30}));
app.get("/api/health",(req,res)=>res.json({status:"ok"}));
app.use("/api/auth",authRoutes);app.use("/api/products",productRoutes);app.use("/api/inventory",inventoryRoutes);app.use("/api/sales",salesRoutes);app.use("/api/reports",reportRoutes);
app.use(notFound);app.use(errorHandler);
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`API listening on ${port}`))).catch(e=>{console.error(e);process.exit(1)});
